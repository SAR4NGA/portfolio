const GH_USER = 'SAR4NGA'
const EXCLUDE = ['portfolio', 'SAR4NGA']
const { writeFileSync } = await import('fs')

const MANUAL_DESCRIPTIONS = {
  'busapp': 'A Flutter-based mobile app for real-time bus tracking, route planning, and public transit information. Designed to help commuters find nearby bus stops, track bus locations, and plan their journeys efficiently.',
  'inflex_mobile': 'A cross-platform Flutter mobile application with native integrations, designed for flexible and scalable mobile experiences across iOS and Android. Utilizes platform channels for native functionality and efficient resource management.',
  'SAR4NGA.github.io': "Pasindu Saranga's personal GitHub Pages site and portfolio.",
}

function toTitle(name) {
  return name
    .replace(/[-_]/g, ' ')
    .replace(/\b\w/g, c => c.toUpperCase())
}

function shuffle(arr) {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]]
  }
  return arr
}

/**
 * Fetch the raw README.md for a given repo.
 * Tries both 'main' and 'master' branches.
 */
async function fetchReadme(repoName) {
  for (const branch of ['main', 'master']) {
    try {
      const url = `https://raw.githubusercontent.com/${GH_USER}/${repoName}/${branch}/README.md`
      const res = await fetch(url)
      if (res.ok) {
        const text = await res.text()
        // Trim excessively long READMEs to keep bundle size reasonable
        return text.length > 8000 ? text.slice(0, 8000) + '\n\n[... truncated]' : text
      }
    } catch { /* try next branch */ }
  }
  return ''
}

async function main() {

  const res = await fetch(`https://api.github.com/users/${GH_USER}/repos?per_page=100&sort=updated`)
  const repos = await res.json()
  if (!Array.isArray(repos)) {
    console.warn(`GitHub API limit or error:`, repos?.message || repos)
    console.warn(`Using existing src/data/projects.ts dataset.`)
    return
  }

  const filtered = repos.filter(r => !r.fork && !EXCLUDE.includes(r.name))

  console.log(`Found ${filtered.length} repos (excluding forks, portfolio, profile)`)


  const projects = []
  const readmes = {}

  for (const repo of filtered) {
    console.log(`  Fetching languages for ${repo.name}...`)
    let tech = []
    try {
      const langRes = await fetch(repo.languages_url)
      const langData = await langRes.json()
      tech = Object.keys(langData).sort((a, b) => langData[b] - langData[a])
    } catch {
      if (repo.language) tech = [repo.language]
    }

    if (tech.length === 0 && !repo.description && !MANUAL_DESCRIPTIONS[repo.name]) {
      console.log(`  Skipping ${repo.name} (no languages, no description)`)
      continue
    }

    // Fetch README content
    console.log(`  Fetching README for ${repo.name}...`)
    const readme = await fetchReadme(repo.name)
    if (readme) {
      readmes[repo.html_url] = readme
      console.log(`    ✓ README fetched (${readme.length} chars)`)
    } else {
      console.log(`    ✗ No README found`)
    }

    projects.push({
      title: toTitle(repo.name),
      description: MANUAL_DESCRIPTIONS[repo.name] || repo.description || '',
      tech,
      github: repo.html_url,
      demo: repo.homepage || undefined,
    })
  }

  shuffle(projects)

  const content = `export interface Project {
  title: string
  description: string
  tech: string[]
  github: string
  demo?: string
  image?: string
}

export const projects: Project[] = ${JSON.stringify(projects, null, 2).replace(/\"([^\"]+)\":/g, '$1:')}
`

  writeFileSync('src/data/projects.ts', content, 'utf-8')
  console.log(`Wrote ${projects.length} projects to src/data/projects.ts`)

  // Write README data file
  const readmeContent = `// Auto-generated by scripts/fetch-projects.mjs — do not edit manually
// Maps GitHub repo URL → raw README.md content

export const projectReadmes: Record<string, string> = ${JSON.stringify(readmes, null, 2)}
`
  writeFileSync('src/data/projectReadmes.ts', readmeContent, 'utf-8')
  console.log(`Wrote ${Object.keys(readmes).length} READMEs to src/data/projectReadmes.ts`)
}

main().catch(err => {
  console.error(err)
  process.exit(1)
})
